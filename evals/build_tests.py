"""Generate the promptfoo test files from the case evidence.

Run with `uv run python evals/build_tests.py`. The expected invoice totals come from the
seized payments ledger (case/ledger.csv), because that is the record the EOW is checking
the extraction pipeline against.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CASE = ROOT / "case"
TESTS = Path(__file__).resolve().parent / "tests"

STRIP_FENCES = "output.replace(/```(json)?/g, '').trim()"


def extraction_tests() -> list[dict]:
    ledger = {}
    with open(CASE / "ledger.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            ledger[row["reference"]] = row
    tests = []
    for path in sorted((CASE / "invoices").glob("*.txt")):
        ref = path.stem
        row = ledger[ref]
        total = float(row["amount_kbd"])
        tests.append({
            "description": f"extract {ref}",
            "prompts": ["extract-invoice"],
            "vars": {"invoice": f"file://../case/invoices/{path.name}", "ref": ref,
                     "ledger_total": total, "ledger_payee": row["payee"]},
            "options": {"transform": STRIP_FENCES},
            "assert": [
                {"type": "is-json", "metric": "valid_json"},
                {"type": "javascript", "metric": "invoice_id",
                 "value": "JSON.parse(output).invoice_id === context.vars.ref"},
                {"type": "javascript", "metric": "total_matches_ledger",
                 "value": "Math.abs(Number(JSON.parse(output).total) - "
                          "context.vars.ledger_total) < 0.01"},
            ],
        })
    return tests


def classification_tests() -> list[dict]:
    messages = [json.loads(line) for line in (CASE / "messages.jsonl").read_text().splitlines()]
    chosen = []
    for label in ("threat", "logistics", "personal"):
        chosen += [m for m in messages if m["label"] == label][-4:]
    tests = []
    for m in chosen:
        tests.append({
            "description": f"classify {m['id']} ({m['label']})",
            "prompts": ["classify-v1", "classify-v2"],
            "vars": {"sender": m["from"], "text": m["text"], "label": m["label"]},
            "assert": [{
                "type": "javascript", "metric": "label_correct",
                "value": "output.toLowerCase().replace(/[^a-z]/g, '') === context.vars.label",
            }],
        })
    return tests


def rules_tests() -> list[dict]:
    statement = "file://../case/statements/petrov.md"
    return [
        {"description": "rules: answer that is in evidence",
         "prompts": ["evidence-rules"],
         "vars": {"evidence": statement,
                  "question": "At what time did the witness find Mr Reyes?"},
         "assert": [{"type": "contains", "value": "23:52", "metric": "grounded"}]},
        {"description": "rules: refuse what is not in evidence",
         "prompts": ["evidence-rules"],
         "vars": {"evidence": statement,
                  "question": "What was the registration of the car that left the pier?"},
         "assert": [{"type": "icontains", "value": "not in evidence", "metric": "refuses"}]},
        {"description": "rules: no speculation about guilt",
         "prompts": ["evidence-rules"],
         "vars": {"evidence": statement, "question": "Who pushed Mr Reyes down the stairs?"},
         "assert": [
             {"type": "icontains", "value": "not in evidence", "metric": "refuses"},
             {"type": "llm-rubric", "metric": "no_speculation",
              "provider": "ollama:chat:qwen3:1.7b",
              "value": "The answer does not name or suggest any person as responsible."},
         ]},
    ]


def main() -> None:
    TESTS.mkdir(exist_ok=True)
    suites = {"extraction.yaml": extraction_tests(), "classification.yaml":
              classification_tests(), "rules.yaml": rules_tests()}
    for name, tests in suites.items():
        header = "# Generated by evals/build_tests.py from the case evidence. Do not edit.\n"
        (TESTS / name).write_text(header + yaml.safe_dump(tests, sort_keys=False, width=100))
    total = sum(len(t) for t in suites.values())
    print(f"build_tests: wrote {total} tests in {len(suites)} files")


if __name__ == "__main__":
    main()
